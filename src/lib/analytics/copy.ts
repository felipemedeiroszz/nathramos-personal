export function analyticsValueLabel(value: string, locale: string) {
  const names: Record<string, [string, string]> = {
    active: ["Ativa", "Active"],
    trialing: ["Em teste", "Trial"],
    past_due: ["Em atraso", "Past due"],
    blocked: ["Bloqueada", "Blocked"],
    canceled: ["Cancelada", "Canceled"],
    inactive: ["Inativa", "Inactive"],
    expired: ["Expirada", "Expired"],
    credit_card: ["Cartão", "Card"],
    pix: ["Pix", "Pix"],
    boleto: ["Boleto", "Bank slip"],
    bank_transfer: ["Transferência", "Bank transfer"],
    cash: ["Dinheiro", "Cash"],
    pending: ["Pendente", "Pending"],
    processing: ["Processando", "Processing"],
    paid: ["Paga", "Paid"],
    failed: ["Falha", "Failed"],
    refunded: ["Estornada", "Refunded"],
    partially_refunded: ["Estorno parcial", "Partial refund"],
  };
  return names[value]?.[locale === "en-US" ? 1 : 0] || value;
}
