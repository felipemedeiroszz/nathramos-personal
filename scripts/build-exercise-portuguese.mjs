function translatedName(name) {
  const reviewed = reviewedNames[name.toLowerCase()];
  if (reviewed) return reviewed;
  const native = nativeNames.get(normalize(name));
  if (native) return native;
  let result = name.toLowerCase();
  let equipment = "";
  for (const [prefix, label] of Object.entries(equipmentPrefixes)) {
    if (result.startsWith(prefix + " ")) {
      equipment = label;
      result = result.slice(prefix.length).trim();
      break;
    }
  }
  let movement = "";
  for (const [phrase, label] of Object.entries(movementPhrases).sort(
    (a, b) => b[0].length - a[0].length,
  )) {
    const regex = new RegExp(
      `(?<![a-z])${phrase.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}(?![a-z])`,
    );
    if (regex.test(result)) {
      movement = label;
      result = result.replace(regex, " ").trim();
      break;
    }
  }
  const placeholders = [];
  for (const [from, to] of Object.entries(phrases).sort(
    (a, b) => b[0].length - a[0].length,
  )) {
    const regex = new RegExp(
      `(?<![a-z])${from.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}(?![a-z])`,
      "g",
    );
    result = result.replace(regex, () => {
      const index = placeholders.push(to) - 1;
      return `§${index}§`;
    });
  }
  result = result.replace(/[a-z]+/g, (word) => {
    if (words[word]) return words[word];
    if (proper.has(word)) return word;
    missing.add(word);
    return word;
  });
  result = result
    .replace(/§(\d+)§/g, (_, index) => placeholders[Number(index)])
    .replace(/\s+/g, " ")
    .trim();
  const label = [movement, result, equipment].filter(Boolean).join(" — ");
  return label.charAt(0).toUpperCase() + label.slice(1);
}
function translatedSteps(row) {
  return row.instruction_steps.pt.map((step, index) => {
    const english = row.instruction_steps.en[index] || "";
    const grip = /\boverhand\b/i.test(english)
      ? "pronada"
      : /\bunderhand\b/i.test(english)
        ? "supinada"
        : null;
    if (!grip) return step;
    // Upstream machine translation sometimes reverses grip direction.
    return (
      step
        .replace(
          /com as (?:palmas(?: das mãos)?|mãos) (?:voltadas |viradas )?para (?:cima|baixo|a frente|frente|fora|dentro)/gi,
          `com pegada ${grip}`,
        )
        .replace(
          /com as mãos na posição [“"]?(?:overhand|underhand)[”"]?/gi,
          `com pegada ${grip}`,
        )
        .replace(
          /(?:uma )?pegada (?:por cima|por baixo|supinada|pronada|overhand|underhand)/gi,
          `pegada ${grip}`,
        )
        .replace(/[“"]?(?:overhand|underhand)[”"]?/gi, `pegada ${grip}`) +
      ` Use pegada ${grip}.`
    );
  });
}
